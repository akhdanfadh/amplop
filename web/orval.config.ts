import { defineConfig, defineTransformer } from "orval";

// The transport reads JSON only. An operation whose success answers
// something else, e.g. a message body for a frame or an attachment, is
// loaded by the browser itself, never called, so it gets no function.
const jsonOperations = defineTransformer((spec) => {
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    if (item === undefined) {
      continue;
    }
    for (const method of ["get", "put", "post", "delete", "patch"] as const) {
      const answersOther = Object.entries(item[method]?.responses ?? {}).some(
        ([status, response]) =>
          status.startsWith("2") &&
          typeof response === "object" &&
          response !== null &&
          "content" in response &&
          typeof response.content === "object" &&
          response.content !== null &&
          !("application/json" in response.content),
      );
      if (answersOther) {
        delete item[method];
      }
    }
    if (!["get", "put", "post", "delete", "patch"].some((method) => method in item)) {
      delete spec.paths?.[path];
    }
  }
  return spec;
});

// `pnpm generate` writes one TypeScript function per API operation, a
// TanStack Query hook for it, and the types they use with a Zod schema for
// each, from the OpenAPI document that Go exports.
export default defineConfig({
  inbok: {
    input: {
      target: "../api/generated/openapi.json",
      // Redirects are addresses another site sends the browser to, e.g.
      // Google's return to inbok; a call from the web app would use up what
      // they carry. Their schemas stay, e.g. ConnectOutcome, which the
      // landing route reads.
      filters: { mode: "exclude", tags: ["Redirects"], includeUnreferencedSchemas: true },
      override: { transformer: jsonOperations },
    },
    output: {
      target: "src/api/generated/inbok.ts",
      // Delete the old output first, so a removed operation disappears.
      clean: true,
      // Hooks such as useGetHealth(), on top of plain fetch functions.
      client: "react-query",
      httpClient: "fetch",
      // Types as Zod schemas, which check a response at runtime.
      schemas: { path: "src/api/generated/model", type: "zod" },
      // Prefix paths with the document's `servers` URL: `/api/v0/health`.
      baseUrl: { getBaseUrlFromSpecification: true },
      override: {
        // Keep the API overview out of every generated file's header.
        header: ({ title, version }) => [
          "Generated by orval 🍺",
          "Do not edit manually.",
          title,
          `OpenAPI spec version: ${version}`,
        ],
        // Every generated function sends its request through transport.
        mutator: { path: "src/api/transport.ts", name: "transport" },
        // Return the success body itself; failures throw ApiError instead.
        fetch: {
          includeHttpResponseReturnType: false,
          forceSuccessResponse: true,
          // Required by the next option. Orval's own check never runs with
          // a mutator; transport runs it instead.
          runtimeValidation: true,
        },
        // Pass each response's schema to transport, which checks the body.
        includeZodSchemaInArguments: true,
        // Pinned, so the output never depends on which Zod Orval detects:
        // its own dependencies include Zod 3.
        zod: { version: 4 },
      },
    },
  },
});
